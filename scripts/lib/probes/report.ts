/**
 * Renders a probe run as Markdown: summary table, a per-deviation index for whoever updates
 * spec/deviations.md, each finding with its scrubbed evidence, the checks that were not probed,
 * and the cleanup list of created test data. All sevDesk data in it was scrubbed on capture.
 */
import { fenceBlock } from "../../../src/safety/fence.js";
import type { Exchange } from "./core.js";
import type { ProbeResult, RunReport } from "./runner.js";

/** Longest evidence body shown per exchange before it is cut. */
const MAX_EVIDENCE_CHARS = 1_500;

const STATUS_LABEL: Readonly<Record<ProbeResult["status"], string>> = {
  confirmed: "confirmed",
  contradicted: "**contradicted**",
  observed: "observed",
  inconclusive: "inconclusive",
  skipped: "skipped",
  error: "**error**",
};

export function renderReport(report: RunReport): string {
  const lines: string[] = [
    "# sevDesk API probe report",
    "",
    `- Date: ${report.date}`,
    `- Account: bookkeeping system version ${report.systemVersion}, API ${hostOf(report.baseUrl)}`,
    `- Mode: ${report.writes ? `with write probes (test data tagged \`${report.tag}\`)` : "read-only"}`,
    `- Generated by \`pnpm probe\` (scripts/probe-api.ts). Personal and company data in the evidence is scrubbed.`,
    "",
    "## Summary",
    "",
    "| Probe | Mode | Result | Deviations |",
    "| --- | --- | --- | --- |",
    ...report.results.map(
      (result) =>
        `| [${result.id}](#${anchor(result.id)}) | ${result.mode} | ${STATUS_LABEL[result.status]} | ` +
        `${result.deviations.map((deviation) => `${deviation.id} (${deviation.verdict})`).join(", ") || "–"} |`,
    ),
    "",
    "## By deviation entry",
    "",
    ...deviationIndex(report.results),
    "",
    "## Findings",
    "",
  ];

  for (const result of report.results) {
    lines.push(
      `### ${result.id}`,
      "",
      `**${escapeInline(result.title)}** · ${result.mode} · ${STATUS_LABEL[result.status]}`,
      "",
    );
    lines.push(`- Question: ${escapeInline(result.question)}`);
    lines.push(`- Finding: ${escapeInline(result.finding)}`);
    if (result.deviations.length > 0) {
      lines.push(
        `- Deviations: ${result.deviations.map((d) => `${d.id} ${d.verdict}`).join(", ")}`,
      );
    }
    lines.push("");
    if (result.evidence.length > 0) {
      lines.push(
        "<details><summary>Evidence (" + String(result.evidence.length) + " requests)</summary>",
        "",
      );
      for (const exchange of result.evidence) lines.push(...renderExchange(exchange), "");
      lines.push("</details>", "");
    }
    for (const attachment of result.attachments ?? []) {
      lines.push(
        `<details><summary>${escapeInline(attachment.label)}</summary>`,
        "",
        // The runner capped the content already; the fence is longer than any backtick run in it.
        fenceBlock(attachment.content, attachment.language ?? "text", Number.MAX_SAFE_INTEGER),
        "",
        "</details>",
        "",
      );
    }
  }

  lines.push("## Not probed (manual)", "");
  for (const check of report.notProbed) {
    const ids = check.deviations.length > 0 ? ` (${check.deviations.join(", ")})` : "";
    lines.push(`- ${check.what}${ids}: ${check.why}`);
  }
  lines.push("", "## Created test data (cleanup)", "");
  if (report.created.length === 0) {
    lines.push("Nothing was created.");
  } else {
    lines.push(
      "Finalized documents cannot be deleted in sevDesk; drafts and contacts can (web app). The trial account " +
        "and everything in it disappears when the trial is cancelled.",
      "",
      "| Object | Id | State | Created by |",
      "| --- | --- | --- | --- |",
      ...report.created.map(
        (record) =>
          `| ${record.objectName} | ${record.id} | ${escapeCell(record.state)} | ${record.probe} |`,
      ),
    );
  }
  return `${lines.join("\n")}\n`;
}

function renderExchange(exchange: Exchange): string[] {
  const head = `${exchange.request} → ${exchange.status}${exchange.contentType === undefined ? "" : ` (${exchange.contentType})`}`;
  const parts = [`- \`${head.replace(/`/g, "'")}\``];
  if (exchange.requestBody !== undefined)
    parts.push(...fenced("request body", exchange.requestBody));
  if (exchange.error !== undefined) parts.push(...fenced("error", exchange.error));
  if (exchange.body !== undefined) parts.push(...fenced("response", exchange.body));
  return parts;
}

function fenced(label: string, value: unknown): string[] {
  const text = typeof value === "string" ? value : JSON.stringify(value, null, 2);
  const cut =
    text.length > MAX_EVIDENCE_CHARS
      ? `${text.slice(0, MAX_EVIDENCE_CHARS)}\n… (${text.length - MAX_EVIDENCE_CHARS} more characters)`
      : text;
  const fence = cut.includes("```") ? "````" : "```";
  return [
    `  ${label}:`,
    "",
    `  ${fence}`,
    ...cut.split("\n").map((line) => `  ${line}`),
    `  ${fence}`,
  ];
}

function deviationIndex(results: readonly ProbeResult[]): string[] {
  const byId = new Map<string, string[]>();
  for (const result of results) {
    for (const deviation of result.deviations) {
      const list = byId.get(deviation.id) ?? [];
      list.push(`${result.id}: ${deviation.verdict}`);
      byId.set(deviation.id, list);
    }
  }
  return [...byId.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([id, entries]) => `- ${id}: ${entries.join("; ")}`);
}

function hostOf(baseUrl: string): string {
  try {
    return new URL(baseUrl).host;
  } catch {
    return "unknown";
  }
}

/** GitHub-style heading anchor for a probe id (lower case, ids have no spaces). */
function anchor(id: string): string {
  return id.toLowerCase().replace(/[^a-z0-9-]/g, "");
}

function escapeInline(text: string): string {
  return text.replace(/\r?\n/g, " ").replace(/</g, "&lt;");
}

/** One Markdown table cell: backslashes first, then pipes, on one line. */
function escapeCell(text: string): string {
  return escapeInline(text).replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
}
