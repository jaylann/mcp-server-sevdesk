describe("attachments in the runner and the report", () => {
  function attaching(content: string, count = 1): ProbeDefinition {
    return {
      id: "read-attach",
      title: "attach",
      mode: "read",
      question: "Does the report show attachments in full?",
      deviations: ["NEW"],
      run: () =>
        Promise.resolve({
          verdict: "observed",
          finding: "ok",
          attachments: Array.from({ length: count }, (_, index) => ({
            label: `Candidate ${index}\nsecond line`,
            language: "xml",
            content,
          })),
        }),
    };
  }

  async function run(probe: ProbeDefinition) {
    const client = new ScriptedClient(() => ({ objects: { version: "2.0" } }));
    return runProbes(options(client, { probes: [probe], allowWrites: false }));
  }

  it("scrubs attachments again with the run scrubber", async () => {
    const report = await run(attaching(`<a>${TOKEN} hans@huber.de</a>`));
    expect(report.results[0]?.attachments).toEqual([
      {
        label: "Candidate 0 second line",
        language: "xml",
        content: "<a><redacted> person1@example.com</a>",
      },
    ]);
    const markdown = renderReport(report);
    expect(() => {
      assertNoSecrets(markdown, [TOKEN]);
    }).not.toThrow();
    expect(markdown).toContain("<details><summary>Candidate 0 second line</summary>");
  });

  it("caps each attachment and the whole report with a visible marker", async () => {
    // Short tokens, like XML: the scrubber's patterns are slow on one endless word.
    const filler = (length: number) => "<a>1</a>\n".repeat(length / 9 + 1).slice(0, length);
    const single = await run(attaching(filler(MAX_ATTACHMENT_CHARS + 10)));
    expect(single.results[0]?.attachments?.[0]?.content).toBe(
      `${filler(MAX_ATTACHMENT_CHARS)}\n[truncated 10 chars]`,
    );
    const many = await run(attaching(filler(MAX_ATTACHMENT_CHARS), 5));
    const contents = many.results[0]?.attachments?.map((item) => item.content) ?? [];
    const kept = contents.reduce(
      (sum, item) => sum + item.replace(/\n\[truncated \d+ chars\]$/, "").length,
      0,
    );
    expect(kept).toBe(MAX_REPORT_ATTACHMENT_CHARS);
    expect(contents[4]).toBe(`\n[truncated ${MAX_ATTACHMENT_CHARS} chars]`);
  });

  it("fences an attachment so its backticks cannot close the block", async () => {
    const report = await run(attaching("a ```` b\n</details> c"));
    const markdown = renderReport(report);
    expect(markdown).toContain("`````xml\na ```` b\n</details> c\n`````");
  });

  it("leaves results without attachments unchanged, and assertNoSecrets covers attachments", async () => {
    const plain = await run({
      ...attaching(""),
      run: () => Promise.resolve({ verdict: "observed", finding: "ok" }),
    });
    expect(plain.results[0]).not.toHaveProperty("attachments");
    const forged = {
      ...plain,
      results: [{ ...plain.results[0]!, attachments: [{ label: "x", content: TOKEN }] }],
    };
    expect(() => {
      assertNoSecrets(renderReport(forged), [TOKEN]);
    }).toThrow(/secret/);
  });
});

