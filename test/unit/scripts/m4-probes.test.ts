/**
 * Whether `xml` is well-formed enough for a fixture: one root, balanced tags, quoted attributes,
 * no stray `<` or unescaped `&` (fast-xml-parser's validator is deprecated).
 */
function wellFormed(xml: string): boolean {
  const body = xml.replace(/<\?[\s\S]*?\?>|<!--[\s\S]*?-->/g, "");
  const stack: string[] = [];
  let roots = 0;
  for (const match of body.matchAll(
    /<(\/?)([A-Za-z_][\w.:-]*)((?:\s+[\w.:-]+="[^"<]*")*)\s*(\/?)>|</g,
  )) {
    const [token, close, name, , selfClosing] = match;
    if (token === "<") return false;
    if (close === "/") {
      if (stack.pop() !== name) return false;
      continue;
    }
    if (stack.length === 0) roots += 1;
    if (selfClosing !== "/") stack.push(name ?? "");
  }
  return stack.length === 0 && roots === 1 && !/&(?!amp;|lt;|gt;|quot;|apos;|#)/.test(body);
}

/** A minimal ZIP (stored entries, no data) with these file names. */
function makeZip(names: readonly string[]): Uint8Array {
  const encoder = new TextEncoder();
  const central: number[] = [];
  for (const name of names) {
    const bytes = encoder.encode(name);
    const header = new Uint8Array(46 + bytes.length);
    const view = new DataView(header.buffer);
    view.setUint32(0, 0x02014b50, true);
    view.setUint32(24, 42, true);
    view.setUint16(28, bytes.length, true);
    header.set(bytes, 46);
    central.push(...header);
  }
  const end = new Uint8Array(22);
  const view = new DataView(end.buffer);
  view.setUint32(0, 0x06054b50, true);
  view.setUint16(10, names.length, true);
  view.setUint32(12, central.length, true);
  view.setUint32(16, 4, true);
  return Uint8Array.from([0x50, 0x4b, 0x03, 0x04, ...central, ...end]);
}

