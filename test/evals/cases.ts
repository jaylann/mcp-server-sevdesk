import type { ToolsetName } from "../../src/tools/toolsets.js";
import type { EvalEnv } from "./tools.js";

/** Stands for "the model answered without calling a tool" in `expected` and `secondChoice`. */
export const NO_TOOL = "(no tool)";

/**
 * One tool-selection case: a user request, the server configuration it is asked under, and which
 * first calls count as right.
 */
export interface EvalCase {
  /** Unique, kebab-case; also the cassette file name. */
  readonly id: string;
  readonly lang: "de" | "en";
  /** The toolset the request belongs to (for the per-toolset summary). */
  readonly toolset: ToolsetName;
  /**
   * `positive`: the right tool is offered. `negative`: the user asks for something the
   * configuration does not allow; the right reaction is to say so (no tool) or to check the
   * permissions (`sevdesk_account_info`), never a workaround.
   */
  readonly kind: "positive" | "negative";
  readonly env: EvalEnv;
  readonly prompt: string;
  /** First calls that score 1. {@link NO_TOOL} means answering without a tool. */
  readonly expected: readonly string[];
  /** Reasonable but not ideal first calls (score 0.5), e.g. a read before a write. */
  readonly secondChoice?: readonly string[];
  /** Negative cases: tools the env must not offer (the premise of the case). */
  readonly absent?: readonly string[];
  readonly notes: string;
}

